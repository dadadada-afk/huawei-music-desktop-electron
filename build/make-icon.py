"""Derives build/icon.ico, build/icon.png and src/main/icons.ts from build/icon-source.png.

The artwork is a fixed design (the red rounded square with the white headphones); this script only
resamples it, so the app icon and the tray glyph can never drift apart from the approved design.

Run: python build/make-icon.py
"""
from __future__ import annotations

import base64
import io
from pathlib import Path

import numpy as np
from PIL import Image

OUT = Path(__file__).resolve().parent
SOURCE = OUT / "icon-source.png"
SIZES = (16, 24, 32, 48, 64, 128, 256)
TRAY_SIZE = 32
# The tray glyph is flat ink so it reads on a light notification area.
TRAY_INK = (23, 24, 28)


def load_source() -> Image.Image:
    art = Image.open(SOURCE).convert("RGBA")
    if art.width != art.height:
        raise SystemExit(f"{SOURCE} must be square, got {art.size}")
    return art


def resized(art: Image.Image, size: int) -> Image.Image:
    """LANCZOS keeps the white glyph's edge crisp; the rounded corners stay transparent."""
    return art.resize((size, size), Image.LANCZOS)


def tray_icon(art: Image.Image, size: int = TRAY_SIZE) -> Image.Image:
    """Lifts the white glyph out of the red field and re-inks it on transparent."""
    small = np.asarray(resized(art, size).convert("RGB"), dtype=np.float32) / 255.0
    # Whiteness of each pixel: the glyph is near 1.0, the red field sits around 0.2.
    whiteness = small.min(axis=2)
    alpha = np.clip((whiteness - 0.62) / 0.30, 0.0, 1.0)
    ink = np.zeros((size, size, 4), dtype=np.uint8)
    ink[..., 0], ink[..., 1], ink[..., 2] = TRAY_INK
    ink[..., 3] = (alpha * 255).astype(np.uint8)
    return Image.fromarray(ink, "RGBA")


TRAY_TS = """// Generated by build/make-icon.py — flat ink headphones for the notification area.
// Regenerate with: python build/make-icon.py
export const TRAY_ICON_PNG_BASE64 = '{payload}';
"""


def write_tray_module(art: Image.Image) -> Path:
    """The tray icon is inlined so it works before out/icon.png has been copied."""
    buffer = io.BytesIO()
    tray_icon(art).save(buffer, format="PNG", optimize=True)
    target = OUT.parent / "src" / "main" / "icons.ts"
    target.write_text(TRAY_TS.format(payload=base64.b64encode(buffer.getvalue()).decode("ascii")),
                      encoding="utf-8")
    return target


def main() -> None:
    art = load_source()
    images = [resized(art, size) for size in SIZES]
    images[-1].save(OUT / "icon.png")
    # Pillow writes every supplied size as its own PNG-compressed frame, which is what Windows 10+
    # expects for a crisp 256px tile in the Start menu and Explorer's extra-large view.
    images[-1].save(OUT / "icon.ico", format="ICO", sizes=[(s, s) for s in SIZES])
    tray = write_tray_module(art)
    print("wrote", OUT / "icon.ico", ",", OUT / "icon.png", "and", tray, "sizes:", SIZES)


if __name__ == "__main__":
    main()
